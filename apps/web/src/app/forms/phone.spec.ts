import { isPhone, maskPhone, normalizePhone } from './phone';

describe('телефон форми (F11-07)', () => {
  it('маска під час введення: український номер групами, інший — плюс і цифри', () => {
    expect(['', '0', '067', '0671234567', '380671234567', '+38 (067) 123-45-67', '4915112345678'].map(maskPhone)).toEqual([
      '',
      '+380',
      '+380 67',
      '+380 67 123 45 67',
      '+380 67 123 45 67',
      '+380 67 123 45 67',
      '+4915112345678',
    ]);
  });

  it('маска не губить цифр і не дає більше 15', () => {
    expect(normalizePhone(maskPhone('+380 67 123 45 67'))).toBe('380671234567');
    expect(normalizePhone('1234567890123456789')).toHaveLength(15);
  });

  it('номер — від 10 до 15 цифр', () => {
    expect([isPhone('+380 67 123 45 67'), isPhone('067 123'), isPhone('1'.repeat(16))]).toEqual([true, false, false]);
  });
});
