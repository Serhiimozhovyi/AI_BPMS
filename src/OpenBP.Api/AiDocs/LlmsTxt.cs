using System.Text;

namespace OpenBP.Api.AiDocs;

/// <summary>MCP tool для інструкції: ім'я, опис, лише читання.</summary>
/// <param name="Name">Ім'я tool'а.</param>
/// <param name="Description">Опис з <c>[Description]</c>.</param>
/// <param name="ReadOnly">Анотація <c>readOnlyHint</c>.</param>
public sealed record LlmsTool(string Name, string? Description, bool ReadOnly);

/// <summary>MCP resource для інструкції.</summary>
/// <param name="Uri">URI або шаблон URI.</param>
/// <param name="Description">Опис.</param>
public sealed record LlmsResource(string Uri, string? Description);

/// <summary>REST-операція для інструкції.</summary>
/// <param name="Method">HTTP-метод.</param>
/// <param name="Path">Шлях з параметрами <c>{id}</c>.</param>
/// <param name="Tag">Розділ OpenAPI.</param>
/// <param name="Summary">Короткий опис.</param>
public sealed record LlmsOperation(string Method, string Path, string Tag, string? Summary);

/// <summary>
/// Текст <c>/llms.txt</c> (F10-02, формат llmstxt.org): інструкція для ШІ-агентів — адреси інстансу, автентифікація,
/// підключення MCP, усі MCP tools/resources і REST-операції (з живого реєстру, тож не застаріває) і покрокові рецепти.
/// Мова — англійська, як і описи MCP tools: її читає модель, а не людина.
/// </summary>
public static class LlmsTxt
{
    /// <summary>Збирає Markdown інструкції.</summary>
    /// <param name="baseUrl">Адреса інстансу без <c>/</c> в кінці.</param>
    /// <param name="tools">MCP tools.</param>
    /// <param name="resources">MCP resources.</param>
    /// <param name="operations">REST-операції <c>/api/v1</c>.</param>
    /// <param name="tagOrder">Порядок розділів REST.</param>
    public static string Build(
        string baseUrl,
        IEnumerable<LlmsTool> tools,
        IEnumerable<LlmsResource> resources,
        IEnumerable<LlmsOperation> operations,
        IEnumerable<string> tagOrder)
    {
        ArgumentNullException.ThrowIfNull(baseUrl);
        var b = baseUrl.TrimEnd('/');
        var sb = new StringBuilder();
        void Line(string text = "") => sb.Append(text).Append('\n');

        Line("# AI_BPMS");
        Line();
        Line("> AI_BPMS is an MCP-native business process automation platform: a trigger starts a graph of nodes that calls any");
        Line("> system through MCP servers. AI_BPMS is itself an MCP server, so an AI agent can inspect connected systems, build,");
        Line("> validate, save and run workflows, read executions, work with data tables and decide human tasks — with exactly the");
        Line("> same services and permissions as the web UI and the REST API.");
        Line();
        Line("This file is generated by the running instance; tool and endpoint lists are always current.");
        Line();

        Line("## Endpoints of this instance");
        Line();
        Line($"- MCP server (Streamable HTTP, stateless): {b}/mcp");
        Line($"- REST API base: {b}/api/v1");
        Line($"- OpenAPI 3.1 document (machine-readable, no auth): {b}/openapi/v1.json");
        Line($"- Swagger UI (for humans): {b}/swagger");
        Line($"- This file: {b}/llms.txt");
        Line($"- Web UI: {b}/");
        Line();

        Line("## Authentication");
        Line();
        Line("- Every MCP and REST call needs an API key: `Authorization: Bearer obp_…`. Without it — HTTP 401 before any MCP exchange.");
        Line("- A human creates the key in the web UI: Settings → API keys (`/settings?section=api-keys`), or via");
        Line("  `POST /api/v1/api-keys`. The key is shown once. Ask the human for it; never guess, print or store it in files you share.");
        Line("- The key carries its user's role: `viewer` reads, `editor` also creates/updates/publishes/runs workflows and tests nodes,");
        Line("  `admin` additionally manages users and connectors in the UI. A key limited to one project sees only that project.");
        Line("- Prefer a dedicated `editor` user and key for the agent, so it can be revoked without affecting people.");
        Line();

        Line("## Connect over MCP");
        Line();
        Line("Claude Code:");
        Line();
        Line("```bash");
        Line($"claude mcp add --transport http openbp {b}/mcp --header \"Authorization: Bearer $OPENBP_API_KEY\"");
        Line("```");
        Line();
        Line("Claude Desktop (`claude_desktop_config.json`, needs Node.js; add `\"--allow-http\"` to args for plain http):");
        Line();
        Line("```json");
        Line("{ \"mcpServers\": { \"openbp\": { \"command\": \"npx\",");
        Line($"  \"args\": [\"-y\", \"mcp-remote\", \"{b}/mcp\", \"--header\", \"Authorization:${{OPENBP_AUTH}}\"],");
        Line("  \"env\": { \"OPENBP_AUTH\": \"Bearer obp_your_key\" } } } }");
        Line("```");
        Line();
        Line("Any other MCP client: transport `http` (Streamable HTTP), URL above, header `Authorization: Bearer obp_…`.");
        Line("OAuth is not supported for `/mcp`; clients that cannot send headers cannot connect.");
        Line();

        Line("## How to work (recipes)");
        Line();
        Line("### Build a new workflow");
        Line();
        Line("1. Read resource `openbp://schema/workflow-format` (JSON Schema of a workflow definition).");
        Line("2. `describe_nodes` — node types and their parameters; `describe_node` for one type in detail.");
        Line("3. `describe_connectors` — connected MCP servers with tools (`serverId`, `toolName`, input/output schemas) for `mcp.tool`/`mcp.poll` nodes.");
        Line("   Use only tools that exist there; integrations are always MCP, there are no built-in `telegram.*`-style nodes.");
        Line("4. Compose the definition (`formatVersion: 1`, `nodes`, `connections`, exactly one trigger). Expressions are `{{ … }}` (JavaScript).");
        Line("5. `validate_workflow` — fix every error by `code` and `path` (e.g. `MCP_TOOL_UNKNOWN`, `PARAMETER_INVALID`) and validate again until `valid: true`.");
        Line("6. `create_workflow` (optionally with `groupId` — the project). The workflow is a draft; `publish_workflow` makes the current version the published one.");
        Line("7. `save_workflow_explanation` — a plain-language explanation for business users (Ukrainian by default).");
        Line("8. Do not activate triggers yourself: a human turns on \"Active\" in the UI after reviewing.");
        Line();
        Line("### Change an existing workflow");
        Line();
        Line("1. `list_workflows` / `get_workflow` — read the current definition and `version`.");
        Line("2. `update_workflow` without `planId` returns a plan (diff and validation errors) and saves nothing.");
        Line("3. Show the plan to the human in plain words; after consent call `update_workflow` again with the same arguments plus `planId`.");
        Line("   `WORKFLOW_PLAN_STALE` / `WORKFLOW_VERSION_CONFLICT` mean someone saved in between — re-read and start over.");
        Line();
        Line("### Run and check");
        Line();
        Line("1. `test_node` — run a single node with sample items before running the whole graph.");
        Line("2. `run_workflow` with `startNodeId` and `startItems` (test items instead of a real trigger event) — returns the execution with steps.");
        Line("3. `get_execution` — state (`success`, `error`, `waiting`, `running`, `cancelled`), error, and input/output items of every node.");
        Line("   `list_executions` lists recent runs. Find the first failed step, fix the node, validate, save, run again.");
        Line("4. Waiting executions: `list_tasks` / `get_task` / `complete_task` for human approvals, `get_execution_stages` / `act_on_stage`");
        Line("   for stages, `resume_execution`, `cancel_execution`, `override_rule` (with a reason) for blocked stage rules.");
        Line();
        Line("### Data tables and project apps");
        Line();
        Line("- `list_tables`, `query_table` read data; `create_table` / `alter_table` work like `update_workflow`: first call returns a plan, second with `planId` applies.");
        Line("- Projects are workflow groups: `list_workflow_groups`, `create_workflow_group`, `move_workflow`; app pages — `list_project_pages`, `upsert_project_page`, `set_project_app`.");
        Line("- `export_project` / `import_project` move a whole project as one JSON template.");
        Line();
        Line("### Rules for agents");
        Line();
        Line("- Never ask for, print or put secrets into workflow definitions; credentials are created by humans in the UI and referenced by id.");
        Line("- Confirm with the human before changes that affect production: publishing, running workflows that send messages or write to external systems.");
        Line("- Errors come as `isError: true` with `{ code, message, errors? }` (MCP) or `application/problem+json` with `code`, `detail`, `errors[]` (REST).");
        Line("  Act on `code`: `BAD_REQUEST`, `FORBIDDEN` (role too low), `NOT_FOUND`, `WORKFLOW_INVALID`, `*_PLAN_STALE`, `WORKFLOW_VERSION_CONFLICT`.");
        Line("- MCP and REST are the same application layer: prefer MCP tools; use REST only for what MCP does not cover.");
        Line();

        var toolList = tools.OrderBy(t => t.Name, StringComparer.Ordinal).ToList();
        Line($"## MCP tools ({toolList.Count})");
        Line();
        foreach (var t in toolList)
        {
            Line($"- `{t.Name}`{(t.ReadOnly ? " (read-only)" : "")}: {OneLine(t.Description)}");
        }

        Line();
        Line("## MCP resources");
        Line();
        foreach (var r in resources.OrderBy(r => r.Uri, StringComparer.Ordinal))
        {
            Line($"- `{r.Uri}`: {OneLine(r.Description)}");
        }

        Line();
        Line("## REST API");
        Line();
        Line($"Full schemas, parameters and examples: {b}/openapi/v1.json (Swagger UI: {b}/swagger). All paths below are relative to {b}.");
        Line("Summaries are in Ukrainian (the product UI language).");
        var order = tagOrder.ToList();
        foreach (var group in operations
                     .GroupBy(o => o.Tag)
                     .OrderBy(g => order.IndexOf(g.Key) is var i && i >= 0 ? i : int.MaxValue)
                     .ThenBy(g => g.Key, StringComparer.Ordinal))
        {
            Line();
            Line($"### {group.Key}");
            Line();
            foreach (var op in group.OrderBy(o => o.Path, StringComparer.Ordinal).ThenBy(o => MethodOrder(o.Method)))
            {
                Line($"- `{op.Method} {op.Path}`{(string.IsNullOrWhiteSpace(op.Summary) ? "" : " — " + op.Summary)}");
            }
        }

        Line();
        Line("## Optional");
        Line();
        Line($"- Webhook triggers: `{b}/webhook/{{path}}` (path is set on the `core.webhook` node; no API key, auth is configured on the node).");
        Line("- Workflow definitions export/import as JSON; the format is versioned by `formatVersion`.");
        return sb.ToString();
    }

    private static string OneLine(string? text) =>
        string.IsNullOrWhiteSpace(text) ? "—" : string.Join(' ', text.Split((char[])['\r', '\n'], StringSplitOptions.RemoveEmptyEntries).Select(s => s.Trim()));

    private static int MethodOrder(string method) => method switch
    {
        "GET" => 0,
        "POST" => 1,
        "PUT" => 2,
        "PATCH" => 3,
        "DELETE" => 4,
        _ => 5,
    };
}
